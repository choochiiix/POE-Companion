// Development-only browser verification. Requires Playwright and installed Edge
// (or set SKILLS_BROWSER to another Playwright channel). No runtime dependency.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { makeServer } from '../crafting-ui/server.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server = makeServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await chromium.launch({ channel: process.env.SKILLS_BROWSER || 'msedge', headless: true });
  const page = await browser.newPage({ viewport: {width:1440,height:1000}, reducedMotion:'reduce' });
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    if (!route.request().url().startsWith(`http://127.0.0.1:${server.address().port}/`)) { external.push(route.request().url()); return route.abort(); }
    return route.continue();
  });
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.evaluate(() => {
    localStorage.clear();
    for (const key of ['poe-companion.character.v1','poe-companion.equipment.v1','poe-companion.tree.v1']) localStorage.setItem(key,'{}');
  });
  await page.reload();
  const skills = page.locator('#skillsPanel');
  await page.locator('#skillsTab').click();
  await skills.getByRole('heading',{name:'Gem library',exact:true}).waitFor();
  assert.equal(await page.locator('.workspace-tabs [aria-pressed=true]').count(),1);
  const name = skills.getByRole('textbox',{name:'New group name',exact:true});
  await name.fill('Main skill'); await name.press('Enter');
  const search = skills.getByRole('searchbox');
  await search.fill('Fireball');
  const fireball = skills.getByRole('article').filter({has:page.getByRole('heading',{name:'Fireball',exact:true})});
  await fireball.locator('button[data-gem]').click();
  await search.fill('Faster Attacks');
  await skills.getByRole('article').filter({has:page.getByRole('heading',{name:'Faster Attacks',exact:true})}).locator('button[data-gem]').click();
  assert.match(await skills.locator('.skill-incompatible').textContent(),/Warning/);
  await name.fill('Movement'); await skills.getByRole('button',{name:'Create group',exact:true}).click();
  await search.fill('Leap Slam');
  await skills.getByRole('article').filter({has:page.getByRole('heading',{name:'Leap Slam',exact:true})}).locator('button[data-gem]').click();
  const groupPicker = skills.getByLabel('Editing group / destination for library gems');
  await groupPicker.selectOption({label:'Main skill'});
  const rename = skills.getByRole('textbox',{name:'Group name',exact:true});
  await rename.fill('Main <skill>'); await rename.press('Tab');
  await rename.fill('Main renamed'); await rename.press('Tab');
  const snapshot = await page.evaluate(() => JSON.parse(localStorage.getItem('poe-companion.skills.v1')));
  assert.equal(snapshot.groups.length,2); assert.equal(snapshot.groups[0].name,'Main renamed');
  assert.equal(snapshot.groups[0].supportIds.length,1);
  await page.reload(); await page.locator('#skillsTab').click();
  await search.fill('Fireball');
  await skills.getByRole('button',{name:'Remove active gem',exact:true}).click();
  await fireball.locator('button[data-gem]').click();
  await search.fill('Faster Attacks');
  await skills.getByRole('button',{name:'Remove Faster Attacks',exact:true}).click();
  assert.equal(await skills.getByRole('article').filter({has:page.getByRole('heading',{name:'Faster Attacks',exact:true})}).locator('button[data-gem]').isEnabled(),true);
  await page.locator('.workspace-tabs button').filter({hasText:'Item library'}).click();
  assert.equal(await skills.isVisible(),false);
  await page.locator('#skillsTab').click();
  await page.locator('#characterTab').click();
  assert.equal(await skills.isVisible(),false);
  await page.locator('#skillsTab').focus(); await page.keyboard.press('Enter');
  assert.equal(await skills.isVisible(),true);
  const tabs = skills.getByRole('tablist',{name:'Gem categories'});
  assert.equal(await tabs.getByRole('tab').count(),10);
  assert.equal(await tabs.getAttribute('aria-orientation'),'vertical');
  const positions = await tabs.getByRole('tab').evaluateAll(nodes => nodes.map(n => ({x:n.getBoundingClientRect().x,y:n.getBoundingClientRect().y})));
  assert.ok(positions.every((p,i)=>p.x===positions[0].x && (!i || p.y>positions[i-1].y)));
  await tabs.getByRole('tab',{name:'Support',exact:true}).click();
  await tabs.getByRole('tab',{name:'Support',exact:true}).press('ArrowDown');
  assert.equal(await tabs.getByRole('tab',{name:'Attacks',exact:true}).getAttribute('aria-selected'),'true');
  await tabs.getByRole('tab',{name:'Attacks',exact:true}).press('End');
  assert.equal(await tabs.getByRole('tab',{name:'Traps',exact:true}).getAttribute('aria-selected'),'true');
  await tabs.getByRole('tab',{name:'Traps',exact:true}).press('Home');
  assert.equal(await tabs.getByRole('tab',{name:'All gems',exact:true}).getAttribute('aria-selected'),'true');
  await search.fill('Faster Attacks');
  await tabs.getByRole('tab',{name:'Support',exact:true}).click();
  assert.equal(await skills.getByRole('article').count(),1);
  assert.equal(await skills.locator('.gem-card.gem-active').count(),0);
  await tabs.getByRole('tab',{name:'Spells',exact:true}).click();
  assert.equal(await search.inputValue(),'Faster Attacks');
  await search.fill('Blade Blast');
  const blade = skills.getByRole('article').filter({has:page.getByRole('heading',{name:'Blade Blast',exact:true})});
  for (const text of ['Cost: (6–16) Mana','Cast time: 0.50 sec','Critical strike chance: 10.00%','Effectiveness of added damage: 70%','Deals (11–309) to (17–464) Physical Damage','Base radius is (0.005–0.1) metres']) assert.ok((await blade.innerText()).includes(text),text);
  await blade.locator('.gem-source-details summary').click();
  assert.ok((await blade.innerText()).includes('is_area_damage'));
  await blade.locator('.gem-source-details summary').click();
  if (process.env.SKILLS_SCREENSHOT) await page.screenshot({path:process.env.SKILLS_SCREENSHOT,fullPage:true});
  if (process.env.SKILLS_CARD_SCREENSHOT) await blade.screenshot({path:process.env.SKILLS_CARD_SCREENSHOT});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await search.fill('nonexistentzzzz');
  assert.equal(await skills.getByText('No gems match these filters.',{exact:true}).count(),1);
  await skills.getByRole('button',{name:'Clear filters',exact:true}).click();
  assert.equal(await tabs.getByRole('tab',{name:'All gems',exact:true}).getAttribute('aria-selected'),'true');
  assert.equal(await skills.locator('.gem-card').count(),60);
  await skills.getByRole('button',{name:'Show more gems',exact:true}).click();
  assert.equal(await skills.locator('.gem-card').count(),120);
  for (const key of ['poe-companion.character.v1','poe-companion.equipment.v1','poe-companion.tree.v1']) assert.equal(await page.evaluate(key => localStorage.getItem(key),key),'{}');
  await skills.getByRole('button',{name:'Delete group',exact:true}).click();
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('poe-companion.skills.v1')))).groups.length,1);
  // Exercise a storage failure with the real mounted UI.
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw Error('Storage denied'); }; });
  await name.fill('Utility'); await name.press('Enter');
  assert.match(await skills.locator('section[aria-label="Saved skill setup planner"]').getByRole('status').textContent(),/Storage unavailable/);
  assert.deepEqual(errors,[]); assert.deepEqual(external,[]);
  console.log('Skills browser checks passed: Blade Blast tooltip values, quality, source diagnostics, groups, replacement/removal, repeated rename, persistence, isolated storage, tab navigation, keyboard, filters, empty results, progressive cards, narrow reflow, reduced motion, storage failure, no external requests.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
}
