import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { makeServer } from '../crafting-ui/server.mjs';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server=makeServer();await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
try {
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  const origin=`http://127.0.0.1:${server.address().port}`;
  await page.route('**/*',route=>{if(!route.request().url().startsWith(origin)){external.push(route.request().url());return route.abort()}return route.continue()});
  await page.goto(origin);
  await page.evaluate(()=>localStorage.setItem('poe-companion.skills.v1','preserve-me'));
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Settings',exact:true});
  await dialog.getByLabel('Display density',{exact:false}).selectOption('compact');
  await dialog.getByLabel('Text size',{exact:false}).selectOption('large');
  await dialog.getByLabel('Motion',{exact:false}).selectOption('reduced');
  assert.deepEqual(await page.locator('html').evaluate(node=>({...node.dataset})),{density:'compact',textSize:'large',motion:'reduced'});
  await page.screenshot({path:'docs/previews/settings.png'});
  await dialog.press('Escape');
  assert.equal(await dialog.isVisible(),false);
  assert.equal(await page.locator('#settingsButton').evaluate(node=>node===document.activeElement),true);
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-text-size'),'large');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await dialog.getByRole('button',{name:'Reset preferences',exact:true}).click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('poe-companion.skills.v1')),'preserve-me');
  assert.equal(await page.locator('html').getAttribute('data-density'),'standard');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await dialog.getByRole('button',{name:'Close settings'}).click();
  await page.evaluate(()=>{Storage.prototype.setItem=function(){throw Error('disabled')}});
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await dialog.getByLabel('Display density',{exact:false}).selectOption('compact');
  assert.ok((await dialog.getByRole('status').innerText()).includes('Storage unavailable'));
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log('Settings passed: live preferences, persistence, Escape/focus return, reset isolation, narrow layout, storage failure and offline runtime.');
} finally {await browser?.close();await new Promise(resolve=>server.close(resolve))}
